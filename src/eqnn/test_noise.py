"""
Noise Robustness Evaluation Module for Equivariant Quantum Neural Networks (EqNN).

This script systematically evaluates the performance of pre-trained Quantum Neural Networks 
under varying levels of quantum inference noise. It leverages Hydra for configuration 
management and supports distributed multi-run executions. Results are isolated into 
unique CSV files per job to prevent I/O race conditions during parallel processing.
"""

